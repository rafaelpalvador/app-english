import sys, asyncio
from playwright.async_api import async_playwright
src=APP
async def run(b,vp,tag):
    pg=await b.new_page(viewport={'width':vp[0],'height':vp[1]})
    errs=[]
    pg.on('pageerror',lambda e: errs.append('PAGEERR '+str(e)))
    pg.on('console',lambda m: errs.append('console:'+m.text) if m.type=='error' and 'ERR_' not in m.text else None)
    html=open(src).read()
    await pg.set_content('<style>body{margin:0}</style><iframe id=f sandbox="allow-scripts allow-forms" style="width:100vw;height:100vh;border:0"></iframe>')
    await pg.evaluate("h=>{document.getElementById('f').srcdoc=h}",html)
    await pg.wait_for_timeout(900)
    f=pg.frames[1]
    async def shot(n): await pg.screenshot(path=f'shots/{tag}_{n}.png')
    async def step(name,coro):
        try: await coro
        except Exception as e: errs.append(f'STEP {name}: {str(e)[:200]}')
    await shot('home')
    await step('nav lib', f.locator('[data-nav="lib"]:visible').first.click())
    await pg.wait_for_timeout(200); await shot('lib')
    await step('open t3', f.locator('.book[data-lesson="t3"]').click())
    await pg.wait_for_timeout(300); await shot('read')
    await step('word', f.locator('#text .w').nth(12).click())
    await pg.wait_for_timeout(300); await shot('gloss')
    await step('ai tab', f.locator('[data-g="tab"][data-v="ai"]').click())
    await pg.wait_for_timeout(2600); await shot('ai')
    await step('chip', f.locator('[data-g="fu"]').first.click())
    await pg.wait_for_timeout(2000)
    await step('status2', f.locator('.st-row [data-v="2"]').click())
    if vp[0]<1180: await step('close0', f.locator('[data-g="close"]').click())
    await step('sent', f.locator('.sbtn').nth(1).click())
    if vp[0]<1180: await step('close1', f.locator('[data-g="close"]').click())
    await pg.wait_for_timeout(200); await shot('sent')
    # expression
    await step('expr word', f.locator('#text .w.x').first.click())
    await step('xsave', f.locator('[data-g="xsave"]').click())
    await shot('expr')
    await step('rtheme', f.locator('[data-tb="rt"][data-v="sepia"]').click())
    await step('hl', f.locator('[data-tb="hl"][data-v="new"]').click())
    await step('play', f.locator('[data-tb="play"]').click())
    await pg.wait_for_timeout(300)
    if vp[0]<1180:
        await step('close gloss', f.locator('[data-g="close"]').click())
    await step('finish', f.locator('[data-tb="finish"]').click())
    await pg.wait_for_timeout(200); await shot('finish')
    await step('fin ok', f.locator('#fin-ok').click())
    await step('q1', f.locator('#mcard .opt').first.click())
    await step('q1n', f.locator('#q-go').click())
    await step('q2', f.locator('#mcard .opt').nth(1).click())
    await step('q2n', f.locator('#q-go').click())
    await pg.wait_for_timeout(200); await shot('done')
    await step('to review', f.locator('#q-rev').click())
    await pg.wait_for_timeout(200); await shot('rvstart')
    await step('go', f.locator('[data-r="go"]').click())
    await pg.wait_for_timeout(200); await shot('card')
    await step('show', f.locator('[data-r="show"]').click())
    await pg.wait_for_timeout(700); await shot('cardback')
    await step('g3', f.locator('[data-r="g"][data-v="3"]').click())
    for m in ['cloze','choice','listen']:
        await step('quit', f.locator('[data-r="quit"]').click())
        await step('nav review', f.locator('[data-nav="review"]:visible').first.click())
        await step('mode '+m, f.locator(f'[data-r="mode"][data-v="{m}"]').click())
        await step('go '+m, f.locator('[data-r="go"]').click())
        await pg.wait_for_timeout(150)
        if m=='choice':
            await step('opt', f.locator('[data-r="opt"]').first.click()); await shot('choice')
            await step('next', f.locator('[data-r="next"]').click())
        else:
            await step('type', f.locator('#rv-in').fill('xyz'))
            await step('submit', f.locator('#rv-form button').click()); await shot(m)
            await step('g1', f.locator('[data-r="g"][data-v="1"]').click())
    await step('words', f.locator('[data-nav="words"]:visible').first.click())
    await pg.wait_for_timeout(200); await shot('words')
    await step('wf phrase', f.locator('[data-wf="phrase"]').click())
    await step('wf learn', f.locator('[data-wf="learn"]').click())
    await step('word row', f.locator('.wr').first.click())
    await pg.wait_for_timeout(200); await shot('wordmodal')
    await step('wm st', f.locator('#wm-st [data-v="3"]').click())
    await step('wm open', f.locator('[data-wm-open]').first.click())
    await pg.wait_for_timeout(300); await shot('fromword')
    await step('prog', f.locator('[data-nav="prog"]:visible').first.click())
    await pg.wait_for_timeout(200); await shot('prog')
    await pg.evaluate("()=>window.scrollTo(0,0)")
    await step('settings', f.locator('[data-open-settings]:visible').first.click())
    await pg.wait_for_timeout(200); await shot('settings')
    await step('dark', f.locator('[data-th="dark"]').click())
    await step('close', f.locator('#mcard [data-close]').first.click())
    await step('home', f.locator('[data-nav="home"]:visible').first.click())
    await pg.wait_for_timeout(200); await shot('home_dark')
    await step('import btn', f.locator('[data-h="import"]').click())
    await step('fill', f.locator('#im-x').fill('The quick brown fox jumps over the lazy dog. It was a sunny day in the park!'))
    await step('imp ok', f.locator('#im-ok').click()); await step('ip ok', f.locator('#ip-ok').click())
    await pg.wait_for_timeout(300); await shot('imported')
    await step('imp word', f.locator('#text .w').nth(2).click())
    await pg.wait_for_timeout(200); await shot('imported_gloss')
    # drag-select phrase on desktop
    print(tag, 'ERRORS:', errs if errs else 'none')
    await pg.close()
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path=CHROME,args=['--no-sandbox'])
        await run(b,(390,844),'m')
        await run(b,(1366,900),'d')
        await b.close()
asyncio.run(main())
